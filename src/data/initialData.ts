// Sample roster generator for Class 1A3 (32 students: H01 -> H32)
export function generateSampleClass1A3(): Student[] {
  const students: Student[] = [];
  for (let i = 1; i <= 32; i++) {
    const code = `H${i < 10 ? '0' + i : i}`;
    students.push({
      id: `STD_${code}`,
      code,
      createdAt: '2026-09-05T07:30:00Z',
      notes: i <= 5 ? 'Học sinh có tiến độ tiếp thu nhanh' : i > 25 ? 'Cần hỗ trợ trực quan thêm' : undefined,
    });
  }
  return students;
}
